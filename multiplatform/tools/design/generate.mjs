import { createRequire } from 'node:module';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { resolve, dirname } from 'node:path';
const require = createRequire(import.meta.url);
const search = process.env.FETCH_DESIGN_MODULES || dirname(fileURLToPath(import.meta.url));
const material = await import(pathToFileURL(require.resolve('@material/material-color-utilities', { paths: [search] })));
const { Resvg } = require(require.resolve('@resvg/resvg-js', { paths: [search] }));
const { Hct, TonalPalette, themeFromSourceColor, argbFromHex, Blend } = material;
const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const source = resolve(root, 'desktopApp/src/jvmMain/kotlin/com/miaadrajabi/span');
const families = [
  ['light', '#285FE8'], ['dark', '#0086B5'], ['black', '#AC6500'],
  ['forest', '#008755'], ['orchid', '#7C45C7'], ['rose', '#BD356D'],
];
const tones = [0, 4, 6, 10, 12, 17, 20, 22, 24, 30, 35, 40, 50, 60, 70, 80, 90, 94, 95, 96, 98, 99, 100];
const hex = (c) => `0x${(c >>> 0).toString(16).toUpperCase()}`;
let out = `// Generated by tools/design/generate.mjs using Google's Material Color Utilities 0.3.0.\n// HCT tonal palettes; regenerate from the six brand seeds, never edit individual tones.\npackage com.miaadrajabi.span\n\nimport androidx.compose.ui.graphics.Color\n\ninternal data class MaterialPalette(\n    val primary: Map<Int, Color>, val secondary: Map<Int, Color>, val tertiary: Map<Int, Color>,\n    val neutral: Map<Int, Color>, val variant: Map<Int, Color>, val error: Map<Int, Color>,\n    val success: Map<Int, Color>, val warning: Map<Int, Color>,\n)\n\ninternal val materialPalettes = mapOf(\n`;
for (const [key, seed] of families) {
  const argb = argbFromHex(seed);
  const hct = Hct.fromInt(argb);
  const theme = themeFromSourceColor(argb);
  const palettes = {
    primary: theme.palettes.primary, secondary: theme.palettes.secondary, tertiary: theme.palettes.tertiary,
    // A tinted neutral range preserves each palette's identity on large desktop surfaces.
    neutral: TonalPalette.fromHueAndChroma(hct.hue, 12), variant: TonalPalette.fromHueAndChroma(hct.hue, 16),
    error: theme.palettes.error,
    success: TonalPalette.fromInt(Blend.harmonize(argbFromHex('#238553'), argb)),
    warning: TonalPalette.fromInt(Blend.harmonize(argbFromHex('#A46700'), argb)),
  };
  out += `    "${key}" to MaterialPalette( // seed ${seed}\n`;
  for (const [role, palette] of Object.entries(palettes)) {
    out += `        ${role} = mapOf(${tones.map(t => `${t} to Color(${hex(palette.tone(t))})`).join(', ')}),\n`;
  }
  out += '    ),\n';
}
writeFileSync(resolve(source, 'MaterialPalettes.kt'), out + ')\n');
const icons = resolve(root, 'desktopApp/icons');
const svg = readFileSync(resolve(icons, 'Fetch.svg'), 'utf8');
writeFileSync(resolve(root, 'desktopApp/src/jvmMain/resources/fetch.svg'), svg);
for (const size of [16, 32, 48, 64, 128, 256, 512, 1024]) {
  const png = new Resvg(svg, { fitTo: { mode: 'width', value: size } }).render().asPng();
  mkdirSync(resolve(icons, 'Fetch.iconset'), { recursive: true });
  if ([16, 32, 128, 256, 512].includes(size)) writeFileSync(resolve(icons, `Fetch.iconset/icon_${size}x${size}.png`), png);
  if ([32, 64, 256, 512, 1024].includes(size)) writeFileSync(resolve(icons, `Fetch.iconset/icon_${size/2}x${size/2}@2x.png`), png);
  if (size === 512) {
    writeFileSync(resolve(icons, 'Fetch.png'), png);
    writeFileSync(resolve(root, 'desktopApp/src/jvmMain/resources/fetch.png'), png);
  }
}
// ICO supports lossless PNG payloads, keeping the same vector-derived artwork on Windows.
const sizes = [16, 32, 48, 64, 128, 256];
const images = sizes.map(size => new Resvg(svg, { fitTo: { mode: 'width', value: size } }).render().asPng());
const header = Buffer.alloc(6 + 16 * sizes.length); header.writeUInt16LE(1, 2); header.writeUInt16LE(sizes.length, 4);
let offset = header.length;
images.forEach((png, i) => { const p = 6 + i * 16; header[p] = sizes[i] % 256; header[p + 1] = sizes[i] % 256; header.writeUInt16LE(1, p + 4); header.writeUInt16LE(32, p + 6); header.writeUInt32LE(png.length, p + 8); header.writeUInt32LE(offset, p + 12); offset += png.length; });
writeFileSync(resolve(icons, 'Fetch.ico'), Buffer.concat([header, ...images]));
console.log('Generated six Material HCT palettes and vector-derived PNG/ICO assets.');
